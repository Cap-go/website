const COUNTRY_CURRENCY = new Map(Object.entries(CURRENCY_COUNTRIES).flatMap(([currency, countries]) => countries.map((country) => [country, currency] as const)))

const COUNTRY_TIER = new Map(Object.entries(TIER_COUNTRIES).flatMap(([tier, countries]) => countries.map((country) => [country, tier as PriceTier] as const)))

export function currencyForCountry(country: string | null | undefined): string | null {
  return (country && COUNTRY_CURRENCY.get(country.toUpperCase())) || null
}

export function priceTierForCountry(country: string | null | undefined): PriceTier {
  return (country && COUNTRY_TIER.get(country.toUpperCase())) || FULL_PRICE_TIER
}
