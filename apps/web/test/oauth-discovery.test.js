import { expect, test } from 'bun:test'
import { loadAuthorizationServerMetadata } from '../src/worker/oauth-discovery.ts'

const upstream = {
  issuer: 'https://capgo.app',
  authorization_endpoint: 'https://api.capgo.app/mcp/oauth/authorize',
  token_endpoint: 'https://api.capgo.app/mcp/oauth/token',
  response_types_supported: ['code'],
  grant_types_supported: ['authorization_code'],
}

const fakeFetch = (body, status = 200) => async () => new Response(JSON.stringify(body), { status })

test('authorization server metadata is served as generated by the API for the capgo.app issuer', async () => {
  expect(await loadAuthorizationServerMetadata(fakeFetch(upstream))).toEqual(upstream)
})

test('metadata naming another issuer is never served from capgo.app', async () => {
  await expect(loadAuthorizationServerMetadata(fakeFetch({ ...upstream, issuer: 'https://api.capgo.app' }))).rejects.toThrow()
  await expect(loadAuthorizationServerMetadata(fakeFetch({}, 503))).rejects.toThrow()
})
